"""Dataset sources (synthetic, CASIA v2, DocTamper) and PyTorch datasets.

Every source yields ``Item(image BGR uint8, mask uint8 {0,1} | None, label 0/1, id)``.
Crops are always taken at multiples of 8 so the JPEG block grid stays aligned for the DCT
stream, and augmentations never resample pixels (that would erase compression traces).
"""

from __future__ import annotations

import csv
import hashlib
import io
import os
import random
from dataclasses import dataclass
from pathlib import Path

import cv2
import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset

IMG_EXT = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".bmp"}


@dataclass
class Item:
    image: np.ndarray
    mask: np.ndarray | None
    label: int
    id: str


def split_of(key: str, val_fraction: float = 0.12) -> str:
    h = int(hashlib.md5(key.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return "val" if h < val_fraction else "train"


def _read(path: Path, flag=cv2.IMREAD_COLOR) -> np.ndarray | None:
    data = np.fromfile(str(path), np.uint8)
    img = cv2.imdecode(data, flag)
    if img is None:  # TIFF variants cv2 can't read
        try:
            pil = Image.open(path)
            img = np.asarray(pil.convert("RGB" if flag == cv2.IMREAD_COLOR else "L"))
            if flag == cv2.IMREAD_COLOR:
                img = cv2.cvtColor(img, cv2.COLOR_RGB2BGR)
        except Exception:  # noqa: BLE001
            return None
    return img


class Source:
    name = "source"

    def __len__(self) -> int:
        return len(self.entries)

    def get(self, i: int) -> Item | None:  # pragma: no cover
        raise NotImplementedError

    def labels(self) -> list[int]:
        return [e[1] for e in self.entries]


class SyntheticSource(Source):
    """Pre-generated by ``ml/generate_synthetic.py`` (index.csv + images/ + masks/)."""

    name = "synthetic"

    def __init__(self, root: str | Path, split: str):
        self.root = Path(root) / split
        self.entries = []
        with open(self.root / "index.csv", newline="") as f:
            for row in csv.DictReader(f):
                self.entries.append((row["file"], int(row["label"]), row.get("mask") or ""))

    def get(self, i: int) -> Item | None:
        file, label, mask = self.entries[i]
        img = _read(self.root / "images" / file)
        m = None
        if mask:
            m = (_read(self.root / "masks" / mask, cv2.IMREAD_GRAYSCALE) > 127).astype(np.uint8)
        return None if img is None else Item(img, m, label, f"synth/{file}")


class Casia2Source(Source):
    """CASIA v2.0: Au/ (authentic), Tp/ (tampered), *_gt.png masks in a Groundtruth folder."""

    name = "casia2"

    def __init__(self, root: str | Path, split: str, require_mask: bool = False):
        root = Path(root)
        au = tp = gt = None
        for d in root.rglob("*"):
            if not d.is_dir():
                continue
            n = d.name.lower()
            if n == "au" and au is None:
                au = d
            elif n == "tp" and tp is None:
                tp = d
            elif ("groundtruth" in n or "ground_truth" in n or n == "gt") and gt is None:
                gt = d
        if au is None or tp is None:
            raise FileNotFoundError(f"CASIA2 Au/ and Tp/ folders not found under {root}")
        gt_map = {}
        if gt is not None:
            for p in gt.iterdir():
                stem = p.stem
                if stem.endswith("_gt"):
                    gt_map[stem[:-3]] = p
        self.entries = []
        for p in sorted(au.iterdir()):
            if p.suffix.lower() in IMG_EXT and split_of(p.name) == split:
                self.entries.append((p, 0, None))
        for p in sorted(tp.iterdir()):
            if p.suffix.lower() not in IMG_EXT or split_of(p.name) != split:
                continue
            m = gt_map.get(p.stem)
            if require_mask and m is None:
                continue
            self.entries.append((p, 1, m))

    def get(self, i: int) -> Item | None:
        p, label, mp = self.entries[i]
        img = _read(p)
        if img is None:
            return None
        mask = None
        if mp is not None:
            m = _read(mp, cv2.IMREAD_GRAYSCALE)
            if m is not None and m.shape == img.shape[:2]:
                mask = (m > 127).astype(np.uint8)
        return Item(img, mask, label, f"casia2/{p.name}")


class DocTamperSource(Source):
    """DocTamper LMDB (keys ``image-%09d`` / ``label-%09d``, ``num-samples``).

    Every DocTamper image contains tampered text, so the label is 1 when the mask is non-empty.
    """

    name = "doctamper"

    def __init__(self, lmdb_dir: str | Path, limit: int | None = None, seed: int = 0):
        import lmdb

        self.path = str(lmdb_dir)
        env = lmdb.open(self.path, readonly=True, lock=False, readahead=False, meminit=False)
        with env.begin(write=False) as txn:
            n = int(txn.get(b"num-samples"))
            self.base = 1 if txn.get(b"image-%09d" % 0) is None else 0
        env.close()
        idx = list(range(n))
        if limit and limit < n:
            random.Random(seed).shuffle(idx)
            idx = sorted(idx[:limit])
        self.entries = [(i, 1, None) for i in idx]
        self._env = None
        self._pid = None

    def _txn(self):
        import lmdb

        if self._env is None or self._pid != os.getpid():  # one env per DataLoader worker
            self._env = lmdb.open(
                self.path, readonly=True, lock=False, readahead=False, meminit=False, max_readers=64
            )
            self._pid = os.getpid()
        return self._env.begin(write=False)

    def get(self, i: int) -> Item | None:
        k = self.entries[i][0] + self.base
        with self._txn() as txn:
            ib = txn.get(b"image-%09d" % k)
            lb = txn.get(b"label-%09d" % k)
        if ib is None:
            return None
        img = cv2.cvtColor(np.asarray(Image.open(io.BytesIO(ib)).convert("RGB")), cv2.COLOR_RGB2BGR)
        mask = None
        if lb is not None:
            m = np.asarray(Image.open(io.BytesIO(lb)).convert("L"))
            mask = (m > 0).astype(np.uint8)
        label = int(mask is not None and mask.any())
        return Item(img, mask, label, f"doctamper/{k}")


# --------------------------------------------------------------------------------------------
# Augmentation helpers


def recompress(img: np.ndarray, rng: random.Random, p: float = 0.5, qmin: int = 70) -> np.ndarray:
    if rng.random() >= p:
        return img
    q = rng.randint(qmin, 100)
    ok, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, q])
    return cv2.imdecode(buf, cv2.IMREAD_COLOR) if ok else img


def flip_rot(img: np.ndarray, mask: np.ndarray, rng: random.Random):
    """Flips / 90 degree rotations keep the 8x8 grid aligned for 8-multiple crops."""
    if rng.random() < 0.5:
        img, mask = img[:, ::-1], mask[:, ::-1]
    k = rng.randint(0, 3) if rng.random() < 0.3 else 0
    if k:
        img, mask = np.rot90(img, k), np.rot90(mask, k)
    return np.ascontiguousarray(img), np.ascontiguousarray(mask)


def pad_to(img: np.ndarray, mask: np.ndarray, size: int):
    h, w = img.shape[:2]
    if h >= size and w >= size:
        return img, mask
    ph, pw = max(0, size - h), max(0, size - w)
    img = cv2.copyMakeBorder(img, 0, ph, 0, pw, cv2.BORDER_REFLECT)
    mask = cv2.copyMakeBorder(mask, 0, ph, 0, pw, cv2.BORDER_CONSTANT, value=0)
    return img, mask


def aligned_crop(img, mask, size: int, rng: random.Random, focus: bool):
    """Random 8-aligned crop; with ``focus`` it is centred near a tampered pixel."""
    img, mask = pad_to(img, mask, size)
    h, w = img.shape[:2]
    if focus and mask.any():
        ys, xs = np.nonzero(mask)
        j = rng.randrange(len(ys))
        cy, cx = (
            ys[j] + rng.randint(-size // 3, size // 3),
            xs[j] + rng.randint(-size // 3, size // 3),
        )
        y0, x0 = cy - size // 2, cx - size // 2
    else:
        y0, x0 = rng.randint(0, h - size), rng.randint(0, w - size)
    y0 = int(np.clip(y0, 0, h - size)) // 8 * 8
    x0 = int(np.clip(x0, 0, w - size)) // 8 * 8
    return img[y0 : y0 + size, x0 : x0 + size], mask[y0 : y0 + size, x0 : x0 + size]


def to_tensor(img: np.ndarray) -> torch.Tensor:
    return (
        torch.from_numpy(np.ascontiguousarray(img[:, :, ::-1].transpose(2, 0, 1))).float() / 255.0
    )


class _Mixture:
    """Weighted sampling across sources (so a huge DocTamper doesn't drown the rest)."""

    def __init__(self, sources: list[Source], weights: list[float] | None):
        self.sources = [s for s in sources if len(s)]
        w = weights or [1.0] * len(self.sources)
        self.weights = np.array(w[: len(self.sources)], np.float64)
        self.weights /= self.weights.sum()

    def sample(self, rng: random.Random) -> Item:
        for _ in range(20):
            s = self.sources[int(np.searchsorted(np.cumsum(self.weights), rng.random()))]
            item = s.get(rng.randrange(len(s)))
            if item is not None and min(item.image.shape[:2]) >= 64:
                return item
        raise RuntimeError("Could not read samples from the configured sources")


class SegDataset(Dataset):
    def __init__(self, sources, size=512, length=4000, weights=None, train=True, seed=0):
        self.mix = _Mixture(sources, weights)
        self.size, self.length, self.train, self.seed = size, length, train, seed

    def __len__(self) -> int:
        return self.length

    def __getitem__(self, i: int):
        rng = random.Random(i + self.seed * 1_000_003 if not self.train else None)
        for _ in range(30):
            item = self.mix.sample(rng)
            # a tampered image without a mask can't supervise pixels (nor serve as a negative)
            if not (item.label == 1 and (item.mask is None or not item.mask.any())):
                break
        mask = item.mask if item.mask is not None else np.zeros(item.image.shape[:2], np.uint8)
        img = item.image
        if self.train:
            img = recompress(img, rng, p=0.35, qmin=75)
        img, mask = aligned_crop(img, mask, self.size, rng, focus=rng.random() < 0.7)
        if self.train:
            img, mask = flip_rot(img, mask, rng)
        return to_tensor(img), torch.from_numpy(mask.astype(np.float32))[None]


class PatchDataset(Dataset):
    """Balanced 128x128 patches: tampered patches overlap the mask boundary region."""

    def __init__(self, sources, patch=128, length=40000, weights=None, train=True, seed=0):
        self.mix = _Mixture(sources, weights)
        self.patch, self.length, self.train, self.seed = patch, length, train, seed

    def __len__(self) -> int:
        return self.length

    def __getitem__(self, i: int):
        rng = random.Random(i + self.seed * 1_000_003 if not self.train else None)
        want_pos = i % 2 == 1
        for _ in range(30):
            item = self.mix.sample(rng)
            img = item.image
            mask = item.mask if item.mask is not None else np.zeros(img.shape[:2], np.uint8)
            if want_pos and not (item.label == 1 and mask.any()):
                continue
            if not want_pos and item.label == 1 and not mask.any():
                continue  # tampered somewhere unknown: can't pick a clean patch safely
            if self.train:
                img = recompress(img, rng, p=0.3, qmin=75)
            crop, cm = aligned_crop(img, mask, self.patch, rng, focus=want_pos)
            cover = float(cm.mean())
            if want_pos and cover < 0.08:
                continue
            if not want_pos and cover > 0:
                continue
            if cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY).std() < 3:
                continue  # flat patch carries no signal (inference skips these too)
            if self.train:
                crop, cm = flip_rot(crop, cm, rng)
            return to_tensor(crop), torch.tensor(int(want_pos))
        crop = np.full((self.patch, self.patch, 3), 128, np.uint8)
        return to_tensor(crop), torch.tensor(0)


def build_sources(names: list[str], split: str, data_root: Path, doctamper_limit: int = 30000):
    """Instantiate whichever requested sources exist on disk."""
    out: list[Source] = []
    for n in names:
        try:
            if n == "synthetic":
                out.append(SyntheticSource(data_root / "synthetic", split))
            elif n == "casia2":
                out.append(Casia2Source(data_root / "datasets" / "CASIA2", split))
            elif n == "doctamper":
                base = data_root / "datasets" / "DocTamper"
                sub = "DocTamperV1-TrainingSet" if split == "train" else "DocTamperV1-TestingSet"
                cand = [p for p in base.rglob("data.mdb")]
                chosen = [p.parent for p in cand if sub.lower() in str(p.parent).lower()]
                if not chosen and cand:
                    chosen = [cand[0].parent]
                if chosen:
                    limit = (
                        doctamper_limit if split == "train" else max(1000, doctamper_limit // 10)
                    )
                    out.append(DocTamperSource(chosen[0], limit=limit))
        except (FileNotFoundError, OSError) as e:
            print(f"[data] skipping {n}: {e}")
    return out
